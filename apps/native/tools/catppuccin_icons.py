"""Regenerates the bundled Catppuccin Mocha file icons and their lookup table.

    curl -L https://codeload.github.com/catppuccin/vscode-icons/tar.gz/refs/heads/main | tar -xz
    python3 -I tools/catppuccin_icons.py vscode-icons-main

Reads `src/defaults/fileIcons.ts` as text — it is never executed — and
writes:

    assets/file-icons/<flavour>/<icon>.svg   the Mocha and Latte icons the table uses
    assets/file-icons/LICENSE        Catppuccin's MIT licence
    src/file_icons_table.rs          file names and extensions → icon

Catppuccin's icons are MIT; see assets/file-icons/LICENSE.
"""
import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
# Associations VS Code makes through a language id alone, which a table of
# names and extensions cannot see.
EXTRA_EXTENSIONS = {"diff": ["diff"]}
FALLBACK = "_file"


def parse(source: str) -> dict:
    body = source[source.index("const fileIcons"):]
    entries = {}
    for m in re.finditer(r"^  '?([\w.-]+)'?: \{(.*?)^  \},", body, re.S | re.M):
        name, inner = m.group(1), m.group(2)
        entry = {}
        for key in ("fileExtensions", "fileNames"):
            found = re.search(key + r":\s*\[(.*?)\]", inner, re.S)
            if found:
                entry[key] = re.findall(r"'([^']*)'", found.group(1))
        entries[name] = entry
    expected = len(re.findall(r"^  '?[\w.-]+'?: \{", body, re.M))
    if len(entries) != expected:
        sys.exit(f"parsed {len(entries)} of {expected} entries; the file's shape changed")
    return entries


def rust_str(text: str) -> str:
    return json.dumps(text)  # JSON string escapes are valid Rust ones here


def main() -> None:
    repo = Path(sys.argv[1])
    entries = parse((repo / "src/defaults/fileIcons.ts").read_text())
    icons_dir = repo / "icons/mocha"
    flavours = ("mocha", "latte")

    names, extensions = {}, {}
    for icon, entry in entries.items():
        if not (icons_dir / f"{icon}.svg").exists():
            continue
        for name in entry.get("fileNames", []):
            names.setdefault(name.lower(), icon)  # the first association wins
        for ext in entry.get("fileExtensions", []) + EXTRA_EXTENSIONS.get(icon, []):
            extensions.setdefault(ext.lower(), icon)

    # The fallback file icon and the plain folder, closed and open.
    used = sorted(set(names.values()) | set(extensions.values()) | {FALLBACK, "_folder", "_folder_open"})
    out = HERE / "assets/file-icons"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for flavour in flavours:
        (out / flavour).mkdir()
        for icon in used:
            shutil.copy(repo / "icons" / flavour / f"{icon}.svg", out / flavour / f"{icon}.svg")
    shutil.copy(repo / "LICENSE", out / "LICENSE")

    lines = [
        "// Generated by tools/catppuccin_icons.py from catppuccin/vscode-icons",
        "// (MIT, see assets/file-icons/LICENSE). Do not edit by hand.",
        "",
        "/// Whole file names, lowercased and sorted.",
        "pub static FILE_NAMES: &[(&str, &str)] = &[",
        *[f"    ({rust_str(k)}, {rust_str(v)})," for k, v in sorted(names.items())],
        "];",
        "",
        "/// Extensions without the leading dot, some compound (`d.ts`), lowercased",
        "/// and sorted.",
        "pub static EXTENSIONS: &[(&str, &str)] = &[",
        *[f"    ({rust_str(k)}, {rust_str(v)})," for k, v in sorted(extensions.items())],
        "];",
        "",
        "/// Every icon the tables name, plus the fallback and the folders, drawn for Mocha.",
        "pub static MOCHA: &[(&str, &[u8])] = &[",
        *[f'    ({rust_str(i)}, include_bytes!("../assets/file-icons/mocha/{i}.svg")),' for i in used],
        "];",
        "",
        "/// The same icons drawn for Latte.",
        "pub static LATTE: &[(&str, &[u8])] = &[",
        *[f'    ({rust_str(i)}, include_bytes!("../assets/file-icons/latte/{i}.svg")),' for i in used],
        "];",
        "",
    ]
    (HERE / "src/file_icons_table.rs").write_text("\n".join(lines))
    print(f"{len(used)} icons, {len(names)} file names, {len(extensions)} extensions")


main()
